def expand(seq: tuple) -> tuple[tuple[str | None, float], ...]:
    steps: list[tuple[str | None, float]] = []
    for item in seq:
        note = item[0]
        dur = item[1]
        vel = float(item[2]) if len(item) > 2 else (0.0 if note is None else 1.0)
        steps.extend([(note, vel)] * int(dur))
    return tuple(steps)


